/** Helper to get habit icon name by habit string */
export function getHabitIconName(name: string): string {
  const n = name.toLowerCase()
  if (n.includes('porn') || n.includes('sex') || n.includes('pmo')) return 'shield'
  if (n.includes('water') || n.includes('drink') || n.includes('hydrate')) return 'drop'
  if (n.includes('sleep') || n.includes('bed') || n.includes('rest')) return 'moon'
  if (n.includes('read') || n.includes('book') || n.includes('study')) return 'book'
  if (n.includes('step') || n.includes('walk') || n.includes('run')) return 'walk'
  if (n.includes('cold') || n.includes('shower') || n.includes('ice')) return 'snow'
  if (n.includes('protein') || n.includes('gym') || n.includes('workout') || n.includes('lift')) return 'dumb'
  if (n.includes('sugar') || n.includes('alcohol') || n.includes('distract')) return 'ban'
  if (n.includes('wake') || n.includes('morning') || n.includes('sun')) return 'sun'
  if (n.includes('focus') || n.includes('target')) return 'target'
  if (n.includes('excuse') || n.includes('flag')) return 'flag'
  if (n.includes('meditat') || n.includes('breath') || n.includes('mind')) return 'heart'
  return 'spark'
}

